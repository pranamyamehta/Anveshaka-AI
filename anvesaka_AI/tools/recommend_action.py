"""Tool 4: recommend_action — LLM picks the incident and explains why.

Remediation steps are ALWAYS copied from the matched playbook entry.
They are NEVER generated by the LLM.

Owner: Member 2

Input  : RecommendArgs (alert_id, optional candidate_incident_id, root_cause, evidence)
Output : Recommendation + list[str] of remediation_steps from the playbook

The actual LLM call that populates candidate_incident_id, root_cause, and
evidence happens in the graph node (nodes.py / finalize_node).  This function
validates the output and performs the step-copying logic so it is impossible
for hallucinated steps to reach the TriageResult.
"""
from __future__ import annotations

import logging
from typing import Optional

from anvesaka_AI.schemas import (
    Decision,
    PlaybookEntry,
    Recommendation,
)
from anvesaka_AI.tools.registry import CONFIDENCE_THRESHOLD

logger = logging.getLogger(__name__)


def build_recommendation(
    *,
    candidate_incident_id: Optional[str],
    root_cause: str,
    evidence: list[str],
    top_score: float,
    playbook_index: dict[str, PlaybookEntry],
) -> tuple[Recommendation, list[str]]:
    """Validate the LLM's choice and copy remediation steps from the playbook.

    Args:
        candidate_incident_id: incident_id chosen by the LLM, or None.
        root_cause: 1–3 sentence explanation grounded in evidence.
        evidence: short fact list (max 8 items).
        top_score: numeric match score (0-1) from lookup_incidents.
        playbook_index: mapping of incident_id → PlaybookEntry.

    Returns:
        (Recommendation, remediation_steps)
        remediation_steps is always from the playbook — never LLM-generated.
    """
    remediation_steps: list[str] = []

    # ------------------------------------------------------------------ #
    # Determine decision
    # ------------------------------------------------------------------ #
    if candidate_incident_id and candidate_incident_id in playbook_index:
        entry = playbook_index[candidate_incident_id]
        if top_score >= CONFIDENCE_THRESHOLD:
            decision = Decision.MATCH_INCIDENT
            # Steps come from the playbook — guaranteed, not generated.
            remediation_steps = entry.remediation_steps or []
            logger.info(
                "recommend_action: MATCH_INCIDENT %s (score=%.2f, %d steps)",
                candidate_incident_id,
                top_score,
                len(remediation_steps),
            )
        else:
            # LLM chose an incident but the score is too low — escalate.
            decision = Decision.ESCALATE_UNKNOWN
            candidate_incident_id = None
            logger.warning(
                "recommend_action: score %.2f < threshold %.2f, escalating instead of matching %s",
                top_score,
                CONFIDENCE_THRESHOLD,
                candidate_incident_id,
            )
    elif candidate_incident_id and candidate_incident_id not in playbook_index:
        # LLM hallucinated an incident_id that doesn't exist.
        logger.error(
            "recommend_action: LLM returned unknown incident_id %r — escalating",
            candidate_incident_id,
        )
        decision = Decision.ESCALATE_UNKNOWN
        candidate_incident_id = None
    else:
        # LLM correctly returned no match.
        decision = Decision.NO_ACTION
        logger.info("recommend_action: NO_ACTION (no candidate)")

    recommendation = Recommendation(
        decision=decision,
        incident_id=candidate_incident_id if decision == Decision.MATCH_INCIDENT else None,
        root_cause=root_cause[:600],
        evidence=evidence[:8],
    )
    return recommendation, remediation_steps


def format_tool_summary(
    candidate_incident_id: Optional[str],
    root_cause: str,
    remediation_steps: list[str],
) -> str:
    """One-line human-readable summary for the tool_trace."""
    if candidate_incident_id:
        return (
            f"Matched {candidate_incident_id}; "
            f"{len(remediation_steps)} playbook steps copied. "
            f"Root cause: {root_cause[:120]}…"
        )
    return f"No match. Root cause: {root_cause[:120]}…"
